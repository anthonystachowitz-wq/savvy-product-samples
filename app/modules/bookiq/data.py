"""Load the Book IQ data files and demo state.

The JSON files are generated by scripts/generate_bookiq.py. The demo state is
the shared per-module store in data/state/bookiq.json. Missing files degrade to
empty structures so the page can show a clear state instead of crashing.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Optional

from app.platform import state as platform_state

MODULE = "bookiq"
DATA_DIR = Path(__file__).resolve().parents[3] / "data" / "modules" / "bookiq"

DEFAULT_STATE: dict[str, Any] = {"households": {}}


def _read(name: str, default: Any) -> Any:
    path = DATA_DIR / name
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return default


def households_payload() -> dict[str, Any]:
    payload = _read("households.json", {})
    return payload if isinstance(payload, dict) else {}


def households() -> list[dict[str, Any]]:
    items = households_payload().get("households")
    return items if isinstance(items, list) else []


def household(household_id: str) -> Optional[dict[str, Any]]:
    for item in households():
        if item.get("id") == household_id:
            return item
    return None


def book() -> dict[str, Any]:
    payload = households_payload().get("book")
    return payload if isinstance(payload, dict) else {}


def as_of() -> str:
    return str(households_payload().get("as_of") or "")


def assumptions() -> dict[str, Any]:
    payload = _read("assumptions.json", {})
    return payload if isinstance(payload, dict) else {}


def eval_cases() -> dict[str, Any]:
    payload = _read("eval_cases.json", {})
    return payload if isinstance(payload, dict) else {}


def eval_report() -> dict[str, Any]:
    payload = _read("eval.json", {})
    return payload if isinstance(payload, dict) else {}


def files_present() -> dict[str, bool]:
    return {
        name: (DATA_DIR / name).is_file()
        for name in ("households.json", "assumptions.json", "eval_cases.json", "eval.json")
    }


def demo_state() -> dict[str, Any]:
    payload = platform_state.load(MODULE, {})
    if not isinstance(payload, dict):
        payload = {}
    if not isinstance(payload.get("households"), dict):
        payload["households"] = {}
    return payload


def decision(household_id: str) -> dict[str, Any]:
    return demo_state()["households"].get(household_id) or {}


def save_decision(household_id: str, entry: dict[str, Any]) -> dict[str, Any]:
    def mutate(payload: Any) -> dict[str, Any]:
        if not isinstance(payload, dict):
            payload = {}
        households = payload.setdefault("households", {})
        if not isinstance(households, dict):
            households = {}
            payload["households"] = households
        households[household_id] = entry
        return payload

    return platform_state.mutate(MODULE, mutate, {"households": {}})


def reset_state() -> None:
    platform_state.reset(MODULE)
